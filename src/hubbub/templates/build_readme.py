"""Build README.md for your GitHub profile. Run: python build_readme.py"""

from pathlib import Path

from hubbub import gh_badges, so_rep, who_am_i, who_am_i_gif  # noqa: F401

intro = who_am_i(
    name="{{name}}",
    likes="{{likes}}",
    learn="{{learn}}",
    work="{{work}}",
    collab="{{collab}}",
    delay=0,
    quiet=True,
)

# Optional: animated intro instead of plain text. Set USE_GIF = True.
USE_GIF = False
if USE_GIF:
    who_am_i_gif(
        name="{{name}}",
        likes="{{likes}}",
        learn="{{learn}}",
        work="{{work}}",
        collab="{{collab}}",
        output="intro.gif",
    )
    intro = ["![](intro.gif)"]

sections = [
    "# Hi there \U0001f44b",
    "<!-- README.md is generated by build_readme.py. Please edit that file. -->",
    "\n\n".join(intro),
    "## GitHub activity",
    gh_badges(
        username="{{username}}",
        badge=["details", "stats", "repo_lang"],
        theme="dark",
    ),
]

# Optional: Stack Overflow reputation badge.
# sections.append(so_rep(username="your-so-username", user_id="00000"))

Path("README.md").write_text("\n\n".join(sections) + "\n", encoding="utf-8")
print("Wrote README.md")
